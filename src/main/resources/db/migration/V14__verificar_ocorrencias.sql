-- RF008 regra 3 / RF009: situações aprovadas (Encerrada será gravada pelo RF012).
ALTER TABLE ocorrencias
    DROP CONSTRAINT ocorrencias_situacao_check,
    ADD CONSTRAINT ocorrencias_situacao_check
        CHECK (situacao IN ('EM_VERIFICACAO', 'CONFIRMADA', 'NAO_CONFIRMADA', 'ENCERRADA'));

-- RF009 regras 2 e 4: cada decisão (e revisão) guarda justificativa interna, representante e instante; nada é apagado.
CREATE TABLE verificacoes_ocorrencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id BIGINT NOT NULL REFERENCES ocorrencias(id) ON DELETE RESTRICT,
    situacao TEXT NOT NULL CHECK (situacao IN ('CONFIRMADA', 'NAO_CONFIRMADA')),
    justificativa TEXT NOT NULL CHECK (justificativa ~ '[^[:space:]]'),
    representante_id BIGINT NOT NULL REFERENCES representantes(id) ON DELETE RESTRICT,
    verificada_em TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_verificacoes_ocorrencia ON verificacoes_ocorrencia(ocorrencia_id);
