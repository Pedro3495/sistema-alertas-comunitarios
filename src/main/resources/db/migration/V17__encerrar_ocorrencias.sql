-- RF012 regras 1 e 4: um único encerramento por ocorrência, com justificativa interna, representante e instante; nada é apagado.
CREATE TABLE encerramentos_ocorrencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id BIGINT NOT NULL UNIQUE REFERENCES ocorrencias(id) ON DELETE RESTRICT,
    justificativa TEXT NOT NULL CHECK (justificativa ~ '[^[:space:]]'),
    representante_id BIGINT NOT NULL REFERENCES representantes(id) ON DELETE RESTRICT,
    encerrada_em TIMESTAMPTZ NOT NULL
);

-- RF012 regras 2 e 3: aviso de encerramento ao lado dos alertas e avisos de alteração.
ALTER TABLE comunicados_ocorrencia
    DROP CONSTRAINT comunicados_ocorrencia_tipo_check,
    ADD CONSTRAINT comunicados_ocorrencia_tipo_check CHECK (tipo IN ('ALERTA', 'ALTERACAO', 'ENCERRAMENTO'));
