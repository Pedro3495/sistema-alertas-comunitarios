CREATE TABLE residencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rua_logradouro TEXT NOT NULL CHECK (length(trim(rua_logradouro)) > 0),
    numero TEXT NOT NULL CHECK (length(trim(numero)) > 0),
    bairro TEXT NOT NULL CHECK (length(trim(bairro)) > 0),
    municipio TEXT NOT NULL CHECK (length(trim(municipio)) > 0),
    complemento TEXT,
    ponto_referencia TEXT,
    area_id BIGINT NOT NULL REFERENCES areas_risco(id) ON DELETE RESTRICT
);
