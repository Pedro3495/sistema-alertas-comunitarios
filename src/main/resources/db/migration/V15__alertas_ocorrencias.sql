-- RF010: alertas emitidos (e avisos de alteração do RF009 regra 4 / RF011 regra 4), preservados sem edição nem exclusão.
CREATE TABLE comunicados_ocorrencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id BIGINT NOT NULL REFERENCES ocorrencias(id) ON DELETE RESTRICT,
    tipo TEXT NOT NULL CHECK (tipo IN ('ALERTA', 'ALTERACAO')),
    titulo TEXT NOT NULL CHECK (titulo ~ '[^[:space:]]'),
    mensagem TEXT NOT NULL CHECK (mensagem ~ '[^[:space:]]'),
    orientacoes TEXT,
    area_id BIGINT NOT NULL REFERENCES areas_risco(id) ON DELETE RESTRICT,
    representante_id BIGINT NOT NULL REFERENCES representantes(id) ON DELETE RESTRICT,
    emitido_em TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_comunicados_orientacoes CHECK (tipo <> 'ALERTA' OR orientacoes ~ '[^[:space:]]')
);
CREATE INDEX ix_comunicados_ocorrencia ON comunicados_ocorrencia(ocorrencia_id);

-- RF010 regras 2, 3, 4 e 7: quem recebeu cada comunicado e se ao menos um canal aceitou o envio.
CREATE TABLE destinatarios_comunicado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comunicado_id BIGINT NOT NULL REFERENCES comunicados_ocorrencia(id) ON DELETE RESTRICT,
    morador_id BIGINT NOT NULL REFERENCES moradores(id) ON DELETE RESTRICT,
    entregue BOOLEAN NOT NULL,
    CONSTRAINT uk_destinatarios_comunicado UNIQUE (comunicado_id, morador_id)
);
CREATE INDEX ix_destinatarios_morador ON destinatarios_comunicado(morador_id);
