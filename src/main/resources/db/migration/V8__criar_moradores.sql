CREATE TABLE moradores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_completo TEXT NOT NULL CHECK (nome_completo ~ '[^[:space:]]'),
    cpf TEXT NOT NULL CHECK (cpf ~ '^[0-9]{11}$'),
    celular TEXT NOT NULL CHECK (celular ~ '^[0-9]{11}$'),
    residencia_id BIGINT NOT NULL REFERENCES residencias(id) ON DELETE RESTRICT,
    canal_credenciais TEXT NOT NULL CHECK (canal_credenciais IN ('SMS', 'WHATSAPP')),
    preferencia_alertas TEXT NOT NULL CHECK (preferencia_alertas IN ('SMS', 'WHATSAPP', 'AMBOS')),
    ativa BOOLEAN NOT NULL,
    CONSTRAINT uk_moradores_cpf UNIQUE (cpf),
    CONSTRAINT uk_moradores_celular UNIQUE (celular)
);
