CREATE TABLE ocorrencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo UUID NOT NULL UNIQUE,
    envio_id UUID NOT NULL,
    registrada_em TIMESTAMPTZ NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('DESASTRE', 'OBRA', 'BARREIRA_CONTENCAO', 'OUTROS')),
    especificacao_outros TEXT,
    descricao TEXT NOT NULL CHECK (descricao ~ '[^[:space:]]'),
    localizacao TEXT NOT NULL CHECK (localizacao ~ '[^[:space:]]'),
    situacao TEXT NOT NULL CHECK (situacao = 'EM_VERIFICACAO'),
    area_id BIGINT NOT NULL REFERENCES areas_risco(id) ON DELETE RESTRICT,
    representante_id BIGINT NOT NULL REFERENCES representantes(id) ON DELETE RESTRICT,
    CONSTRAINT uk_ocorrencias_envio UNIQUE (representante_id, envio_id),
    CONSTRAINT ck_ocorrencias_outros CHECK (tipo <> 'OUTROS' OR (especificacao_outros IS NOT NULL AND especificacao_outros ~ '[^[:space:]]'))
);

CREATE TABLE fotos_ocorrencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id BIGINT NOT NULL REFERENCES ocorrencias(id) ON DELETE RESTRICT,
    ordem INTEGER NOT NULL CHECK (ordem BETWEEN 1 AND 4),
    tipo_midia TEXT NOT NULL CHECK (tipo_midia IN ('image/jpeg', 'image/png', 'image/heic', 'image/heif')),
    conteudo BYTEA NOT NULL CHECK (octet_length(conteudo) BETWEEN 1 AND 5242880),
    CONSTRAINT uk_fotos_ocorrencia_ordem UNIQUE (ocorrencia_id, ordem)
);
