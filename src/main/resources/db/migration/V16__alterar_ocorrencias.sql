-- RF011 regras 1, 5 e 6: cada correção guarda a justificativa interna, o resumo do aviso, o representante e o instante; nada é apagado.
CREATE TABLE alteracoes_ocorrencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id BIGINT NOT NULL REFERENCES ocorrencias(id) ON DELETE RESTRICT,
    justificativa TEXT NOT NULL CHECK (justificativa ~ '[^[:space:]]'),
    resumo TEXT NOT NULL CHECK (resumo ~ '[^[:space:]]'),
    representante_id BIGINT NOT NULL REFERENCES representantes(id) ON DELETE RESTRICT,
    alterada_em TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_alteracoes_ocorrencia ON alteracoes_ocorrencia(ocorrencia_id);
