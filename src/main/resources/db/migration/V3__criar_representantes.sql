CREATE TABLE representantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_completo TEXT NOT NULL CHECK (nome_completo ~ '[^[:space:]]'),
    entidade_publica TEXT NOT NULL CHECK (entidade_publica ~ '[^[:space:]]'),
    login TEXT NOT NULL CHECK (login ~ '[^[:space:]]'),
    senha_hash TEXT NOT NULL CHECK (senha_hash ~ '[^[:space:]]'),
    ativa BOOLEAN NOT NULL,
    troca_senha_obrigatoria BOOLEAN NOT NULL,
    senha_temporaria_expira_em TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_representantes_login UNIQUE (login)
);
